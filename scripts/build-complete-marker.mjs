// The last build step publishes an empty bundle patch that DSH requires.
//
// package.json declares `dsh.bundle.patch` as [cordis.patch.yml, this marker].
// DSH 0.2.2-rc.5 reads every declared patch before it saves an enabled bundle
// (plugin-manager selectBundle -> bundleRows -> loadOverlayPatches) and skips
// the whole bundle layer at boot when one is missing (app-boot
// loadProfileDirectory). A source checkout that was never built therefore
// cannot disable the stock conversation UI, and a profile that already selected
// one falls back to the stock UI on the next cold start. build.mjs empties lib/
// first, so a failed build never leaves the marker behind.
import { existsSync, renameSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** Package-relative path of the marker, as declared in package.json. */
export const BUILD_COMPLETE_PATCH = 'lib/build-complete.patch.yml'

/** Embedded UI packages whose built entries the bundle patch inserts. */
export const RUNTIME_HOST_PACKAGES = [
  'dsh-client-ui-session',
  'dsh-client-ui-conversation',
  'dsh-client-ui-subagent',
  'dsh-client-ui-chat',
]

/** Entries the bundle patch and package.json load; all must exist before the marker. */
export function requiredBuildOutputs() {
  return [
    'lib/index.js',
    'lib/client.js',
    'lib/native-runtime-guard/index.mjs',
    'lib/native-runtime-guard/host-runtime.mjs',
    'lib/typert.host.js',
    'lib/typert.remote-client.js',
    ...RUNTIME_HOST_PACKAGES.flatMap((name) => [
      `runtime-host/${name}/lib/index.js`,
      `runtime-host/${name}/lib/client.js`,
    ]),
  ]
}

const MARKER = `# Generated by scripts/build.mjs after every built entry was verified.
# DSH requires this file (package.json dsh.bundle.patch), so an unbuilt source
# checkout cannot replace the stock conversation UI. Intentionally empty.
[]
`

/**
 * Verify the built entries, then publish the marker atomically.
 * @throws {Error} listing every missing entry; no marker is written then.
 */
export function writeBuildCompleteMarker(root) {
  const missing = requiredBuildOutputs().filter((file) => !existsSync(join(root, file)))
  if (missing.length) throw new Error(`Build incomplete, missing: ${missing.join(', ')}`)
  const target = join(root, BUILD_COMPLETE_PATCH)
  const staged = `${target}.${process.pid}.tmp`
  writeFileSync(staged, MARKER)
  renameSync(staged, target)
}
